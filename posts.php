    <div class="col">
        <p>1. Dzisiaj na&nbsp;Mszy Świętej o&nbsp;godz.&nbsp;12.30 dzieci
        z&nbsp;klas trzecich przyjmą pierwszą Komunię Świętą.</p>
        <p>2. W&nbsp;czwartek 4&nbsp;czerwca Uroczystość Najświętszego Ciała
        i&nbsp;Krwi Chrystusa (Boże Ciało). Msze Święte w&nbsp;naszym kościele
        o&nbsp;godz.&nbsp;7.30, 9.30 i&nbsp;18.00. Mszy Świętej
        o&nbsp;godz.&nbsp;9.30 przewodniczył będzie ksiądz biskup Krzysztof
        Nitkiewicz. Po&nbsp;Mszy Świętej wyruszymy ulicą Mickiewicza
        w&nbsp;procesji z&nbsp;Najświętszym Sakramentem do&nbsp;4&nbsp;ołtarzy.
        Zakończenie procesji przy kościele świętego Michała. Tam też
        po&nbsp;zakończeniu procesji będzie także można uczestniczyć
        w&nbsp;Mszy Świętej.</p>
        <p>3. W&nbsp;przyszłą niedzielę będą w&nbsp;naszej parafii obecne
        Siostry Franciszkanki Niepokalanej. Po&nbsp;Mszach Świętych będzie
        można nabyć książki z&nbsp;ich wydawnictwa.</p>
        <p>4. Dziś kończymy nabożeństwa majowe. W&nbsp;miesiącu czerwcu modlić
        się będziemy litanią do&nbsp;Najświętszego Serca Pana Jezusa
        o&nbsp;godzinie 17.50. W&nbsp;oktawie Uroczystości Bożego Ciała
        litanię będziemy śpiewać podczas procesji o&nbsp;godz.&nbsp;17.40.</p>
        <p>5. Dziś miała się odbyć majówka na&nbsp;statku. Ze&nbsp;względu
        na&nbsp;niski stan wody na Wiśle, została przeniesiona do&nbsp;ogrodów
        domu rekolekcyjnego <em>Quo Vadis</em>. Początek
        o&nbsp;godz.&nbsp;18.00.</p>
        <p>6. W&nbsp;tym tygodniu pierwszy czwartek, piątek i&nbsp;sobota
        miesiąca. Chorych w&nbsp;domach odwiedzimy w&nbsp;piątek
        od&nbsp;godz.&nbsp;8.00. Spowiedź pierwszopiątkowa od&nbsp;godziny
        17.00. W&nbsp;sobotę różaniec wynagradzający o&nbsp;godz.&nbsp;17.00.</p>
        <p>7. W&nbsp;przyszłą niedzielę różaniec o&nbsp;godz.&nbsp;10.45
        i&nbsp;zmiana tajemnic różańcowych.</p>
        <p>8. Tegoroczny Rajd Papieski odbędzie się 13&nbsp;czerwca. Trasa
        wiedzie z&nbsp;Sandomierza do&nbsp;Osieka. Zapisy ruszają
        od&nbsp;1&nbsp;czerwca. Można się zgłaszać osobiście w&nbsp;burze
        Miejskiego Ośrodka Sportu i&nbsp;Rekreacji w&nbsp;Sandomierzu lub
        elektronicznie poprzez formularz zgłoszeniowy.</p>
        <p>9. 20&nbsp;czerwca w&nbsp;Ożarowie odbędzie się diecezjalne
        spotkanie młodych. Z&nbsp;dekanatu organizowany jest wyjazd
        na&nbsp;to&nbsp;wydarzenie. Szczegóły na&nbsp;plakacie. Zapisy
        na&nbsp;autokar u&nbsp;Księdza Proboszcza.</p>
        <p>10. Światowe Dni Młodzieży odbędą się w&nbsp;Seulu w&nbsp;Korei
        Południowej w&nbsp;dniach 3-8&nbsp;sierpnia 2027 roku. Spotkanie
        to&nbsp;będzie wyjątkową okazją do&nbsp;doświadczenia żywego Kościoła,
        wspólnej modlitwy oraz budowania wspólnoty młodych z&nbsp;całego
        świata. Jeśli ktoś myślałby o&nbsp;wyjeździe na&nbsp;to&nbsp;wydarzenie,
        proszony jest o&nbsp;kontakt z&nbsp;księdzem Krystianem.</p>
        <p>11. W&nbsp;tym tygodniu swoją ziemską pielgrzymkę zakończył nasz
        parafianin Józef Wrona. Polećmy go&nbsp;Bożemu miłosierdziu.</p>
        <p>12. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        parafii. Wszystkim obchodzącym imieniny, rocznice i&nbsp;jubileusze
        składamy serdeczne życzenia. Wszystkim Parafianom i&nbsp;Gościom
        życzymy błogosławionej niedzieli.</p>
