    <div class="card-header">
        <h3>30.&nbsp;sierpnia 2026&nbsp;r.</h3>
        <h3>XXII&nbsp;niedziela zwykła, Rok&nbsp;A</h3>
    </div>
    <div class="col">
        <p>1. W&nbsp;tym tygodniu, w&nbsp;czwartek 3&nbsp;września, oddajemy
        cześć świętemu Grzegorzowi Wielkiemu, papieżowi.</p>
        <p>2. We <strong>wtorek 1&nbsp;września</strong> rozpoczęcie nowego
        roku szkolnego. Na&nbsp;Mszę Świętą na&nbsp;godzinę 8.00 zapraszamy
        uczniów i&nbsp;nauczycieli.</p>
        <p>3. W&nbsp;tym tygodniu pierwszy czwartek, piątek i&nbsp;sobota
        miesiąca. Możliwość spowiedzi w&nbsp;piątek od&nbsp;godz.&nbsp;6.10
        i&nbsp;od&nbsp;godziny 17.00.</p>
        <p>4. Chorych w&nbsp;domach odwiedzimy: ksiądz Proboszcz
        w&nbsp;czwartek od&nbsp;godz.&nbsp;8.00, Księża Wikariusze
        w&nbsp;piątek od&nbsp;godz.&nbsp;8.00.</p>
        <p>5. W&nbsp;sobotę różaniec wynagradzający o&nbsp;godz.&nbsp;17.30
        poprowadzi Legion Maryi.</p>
        <p>6. W&nbsp;niedzielę różaniec i&nbsp;zmiana tajemnic różańcowych
        o&nbsp;godz.&nbsp;10.45.</p>
        <p>7. Spotkanie dla kandydatów do&nbsp;bierzmowania z&nbsp;klasy&nbsp;8
        będą odbywać się w&nbsp;pierwsze czwartki miesiąca. Każde spotkanie
        rozpocznie się Mszą Święto o&nbsp;18:00, a&nbsp;po&nbsp;niej katecheza
        w&nbsp;kościele. Pierwsze obowiązkowe spotkanie dla kandydatów
        do&nbsp;bierzmowania z&nbsp;klasy&nbsp;8 z&nbsp;rodzicami odbędzie się
        <strong>3&nbsp;września</strong>, nieobecność kandydatów
        do&nbsp;bierzmowania prosimy o&nbsp;usprawiedliwienie.</p>
        <p>8. Spotkania dla ministrantów od&nbsp;września będą odbywać się
        w&nbsp;poniedziałki. Dla młodszych ministrantów i&nbsp;tych, którzy
        chcieliby zostać ministrantami zbiórki będą w&nbsp;poniedziałki
        o&nbsp;godz.&nbsp;16:00 w&nbsp;kościele. Dla starszych ministrantów
        i&nbsp;lektorów spotkania będą również w&nbsp;poniedziałki, ale
        po&nbsp;Mszy Świętej wieczorowej, ok.&nbsp;18:30. Pierwsze spotkanie
        ministrantów <strong>7&nbsp;września</strong>.</p>
        <p>9. Od&nbsp;września wznawiamy treningi drużyny LSO Sandomierz
        na&nbsp;hali. Dla szkoły średniej zajęcia będą odbywać się
        w&nbsp;każdy poniedziałek na&nbsp;hali sportowej "pod balonem" przy
        szkole podstawowej nr&nbsp;1 od&nbsp;19:30 do&nbsp;21:00. Dla
        młodszych zajęcia będą na&nbsp;hali sportowej szkoły podstawowej
        nr&nbsp;4 w&nbsp;soboty o&nbsp;13. Wejście na&nbsp;halę
        od&nbsp;ul.&nbsp;Cieśli. Pierwsze zajęcia w&nbsp;najbliższą
        <strong>sobotę, 5&nbsp;września</strong>.</p>
        <p>10. Chcielibyśmy reaktywować scholę parafialną. Zapraszamy
        wszystkich chętnych do&nbsp;śpiewania: zarówno dziewczynki, jak
        i&nbsp;chłopców. Próby odbywać się będą w&nbsp;soboty
        o&nbsp;godz.&nbsp;9.00 w&nbsp;salce na&nbsp;plebanii. Pierwsze
        spotkanie w&nbsp;najbliższą <strong>sobotę,
        5&nbsp;września</strong>.</p>
        <p>11. Legion Maryi zaprasza na&nbsp;spotkania w&nbsp;środy
        po&nbsp;Mszy wieczornej.</p>
        <p>12. W&nbsp;przyszły <strong>poniedziałek 7&nbsp;września</strong>
        wyruszy piesza pielgrzymka z&nbsp;Sandomierza do&nbsp;Sulisławic.
        Rozpoczęcie o&nbsp;8.15 w&nbsp;katedrze sandomierskiej. Msza Święta
        w&nbsp;Sulisławicach o&nbsp;godzinie 18.00. Zapisy w&nbsp;dniu wyjścia
        przy katedrze.</p>
        <p>13. W&nbsp;<strong>piątek 11&nbsp;września</strong>, po&nbsp;Mszy
        świętej wieczornej, a&nbsp;więc na&nbsp;godz.&nbsp;18.30 zapraszamy
        rodziców dzieci pierwszokomunijnych, na&nbsp;spotkanie
        organizacyjne.</p>
        <p>14. W&nbsp;<strong>niedzielę 13&nbsp;września</strong>
        o&nbsp;godz.&nbsp;16.00 wystąpi u&nbsp;nas w&nbsp;kościele krakowski
        Teatr Exit. Zobaczymy ich autorskie "Misterium Miłosierdzia", które -
        jak czytamy w&nbsp;recenzjach - potrafi przemeblować serce
        i&nbsp;pocieszyć w&nbsp;największej ciemności. Zapraszamy każdego, kto
        kocha piękną muzykę i&nbsp;poezję, ale przede wszystkim tych, którzy
        pragną wewnętrznego pocieszenia, bo&nbsp;"Misterium Miłosierdzia" daje
        potężną dawkę nadziei. Teatr Exit tworzą niepełnosprawni artyści
        o&nbsp;wyjątkowej wrażliwości i&nbsp;wybitnych zdolnościach
        muzycznych. Towarzyszą im&nbsp;znakomite postaci polskiej sceny
        muzycznej i&nbsp;teatralnej. Niektórzy mówią, że&nbsp;Teatr Exit jest
        perłą polskiej kultury symbolicznej. Warto to&nbsp;sprawdzić
        i&nbsp;przekonać się o&nbsp;tym samemu. Zapraszamy
        na&nbsp;tą&nbsp;duchową i&nbsp;artystyczną ucztę 13&nbsp;września
        o&nbsp;godz.&nbsp;16.</p>
        <p>15. W&nbsp;tym tygodniu zostało wykonane czyszczenie, szlifowanie
        i&nbsp;zabezpieczenie posadzki w&nbsp;naszym kościele. Żeby dłużej
        zachować efekt renowacji zakupiliśmy także maszynę jej czyszczenia
        oraz nowe wycieraczki do&nbsp;kościoła. Dziękujemy za&nbsp;wszelkie
        ofiary złożone na&nbsp;ten cel oraz bardzo dużą pomoc przy przesuwaniu
        ławek i&nbsp;kilkukrotnym sprzątaniu kościoła w&nbsp;tym tygodniu.</p>
        <p>16. Ponieważ przy szlifowaniu nagromadziło się dużo kurzu
        w&nbsp;kościele chcielibyśmy w&nbsp;najbliższą sobotę od&nbsp;godziny
        8.00 zrobić generalne sprzątanie kościoła. Prosimy chętnych
        o&nbsp;zgłoszenie do&nbsp;zakrystii chęci pomocy, tak, żebyśmy
        wiedzieli jakie porządki będziemy mogli zrobić. Pomóc mogą zarówno
        kobiety, jaki i&nbsp;mężczyźni.</p>
        <p>17. W&nbsp;tym tygodniu swoją ziemską pielgrzymkę zakończyli nasi
        parafianie: Bogusław Wnuk, Artur Wydra i Alfred Sobieniak. Polećmy ich
        Bożemu miłosierdziu.</p>
        <p>18. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        parafii. Szczególnie za&nbsp;ofiary składane na&nbsp;prace
        w&nbsp;kościele. Wszystkim obchodzącym imieniny, rocznice, jubileusze
        składamy serdeczne życzenia. Drogim Parafianom i&nbsp;miłym Gościom
        życzymy dobrej niedzieli, a&nbsp;uczniom i&nbsp;nauczycielom
        spokojnego powrotu do&nbsp;szkoły.</p>
