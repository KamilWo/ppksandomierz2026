        <h3>7.&nbsp;czerwca 2026&nbsp;r.</h3>
        <h3>10&nbsp;niedziela zwykła, Rok&nbsp;A</h3>
    </div>
    <div class="col">
        <p>1. Trwamy w&nbsp;oktawie Uroczystości Bożego Ciała. Zapraszamy
        codziennie na&nbsp;procesję eucharystyczną na&nbsp;godz.&nbsp;17.40,
        aby oddać cześć Chrystusowi obecnemu wśród nas w&nbsp;Najświętszym
        Sakramencie. Zakończenie oktawy w&nbsp;czwartek.</p>
        <p>2. W&nbsp;piątek uroczystość Najświętszego Serca Pana Jezusa,
        a&nbsp;w&nbsp;sobotę wspomnienie Niepokalanego Serca Maryi.</p>
        <p>3. W&nbsp;czerwcu modlimy się litanią do&nbsp;Najświętszego serca
        Pana Jezusa: w&nbsp;oktawie podczas procesji,
        a&nbsp;po&nbsp;zakończeniu oktawy na&nbsp;zakończenie codziennej
        adoracji, czyli o&nbsp;17.50.</p>
        <p>4. Chciałbym bardzo podziękować za&nbsp;pomoc w&nbsp;organizacji
        procesji Bożego Ciała. Nie chciałbym nikogo pominąć, więc nie
        wymieniam imiennie. Ale wszystkim, którzy pomogli w&nbsp;kościele,
        przygotowali ołtarz na&nbsp;drodze procesji, pomogli w&nbsp;czasie
        procesji.</p>
        <p>5. Dziękuję za&nbsp;posprzątanie kościoła i&nbsp;terenu wokół
        kościoła, za&nbsp;skoszenie trawy i&nbsp;posadzenie kwiatów rodzicom
        dzieci pierwszokomunijnych. I&nbsp;za&nbsp;wczorajsze sprzątnięcie
        kościoła rodzicom dzieci rocznicowych. W&nbsp;kwietniu kościół
        posprzątali rodzice dzieci bierzmowanych i&nbsp;za&nbsp;tę&nbsp;ich
        pracę także dziękuję.</p>
        <p>6. Rodzicom dzieci pierwszokomunijnych dziękuję bardzo za&nbsp;dar
        ołtarza. Za&nbsp;nowy trybularz oraz ofiarę pieniężną na&nbsp;rzecz
        parafii.</p>
        <p>7. Dnia 12&nbsp;czerwca w&nbsp;rocznicę pobytu św.&nbsp;Jana
        Pawła&nbsp;II w&nbsp;Sandomierzu organizowane jest wynagradzające
        czuwanie modlitewne. O&nbsp;godz.&nbsp;20.45 wspólna modlitwa przy
        figurze Jana Pawła&nbsp;II na&nbsp;Placu Papieskim, następnie
        przemarsz do&nbsp;bazyliki katedralnej, gdzie odbędzie się czuwanie
        modlitewne. Szczegóły na&nbsp;plakacie.</p>
        <p>8. Zapraszamy na&nbsp;tegoroczny Rajd Papieski, który odbędzie się
        13&nbsp;czerwca. Początek tradycyjnie o&nbsp;godz.&nbsp;9.00
        w&nbsp;Sandomierzu. Trasa w&nbsp;tym roku będzie wiodła
        do&nbsp;Osieka. Wszystkie potrzebne informacje dostępne
        są&nbsp;na&nbsp;stronie diecezjalnej.</p>
        <p>9. W&nbsp;sobotę 20&nbsp;czerwca zapraszamy na&nbsp;kolejny
        wieczór uwielbienia.</p>
        <p>10. W&nbsp;niedzielę 21&nbsp;czerwca odbędzie się w&nbsp;naszym
        mieście Marsz dla Życia i&nbsp;Rodziny oraz piknik rodzinny.
        O&nbsp;14.30 w&nbsp;kościele św.&nbsp;Józefa Msza Święta
        w&nbsp;intencji dzieci i&nbsp;rodzin z&nbsp;zawierzeniem rodzin
        św.&nbsp;Józefowi; następnie Marsz dla Życia i&nbsp;Rodziny, który
        przejdzie z&nbsp;kościoła św.&nbsp;Józefa do&nbsp;placu przy
        ul.&nbsp;Żółkiewskiego 9, gdzie w&nbsp;godz.&nbsp;16.00-20.00 odbędzie
        się piknik rodzinny.</p>
        <p>11. Nasza parafialna drużyna sportowa LSO SANDOMIERZ dostała się
        na&nbsp;Mistrzostwa Polski LSO w&nbsp;Gnieźnie. Mistrzostwa odbędą się
        w&nbsp;dniach 28-30 czerwca. W&nbsp;związku z&nbsp;tym w&nbsp;następną
        niedzielę nasi ministranci i&nbsp;lektorzy będą rozdawać
        po&nbsp;Mszach przygotowane słodkie upominki i&nbsp;przy okazji będą
        zbierać do&nbsp;puszek ofiary na&nbsp;organizację wyjazdu. Jeśli ktoś
        chciałby dodatkowo wesprzeć naszą drużynę prosimy o&nbsp;kontakt
        z&nbsp;ks.&nbsp;Wojciechem. Dziękujemy wszystkim osobom, które już
        wspierają drużynę finansowo i&nbsp;duchowo.</p>
        <p>12. Gościmy dziś w&nbsp;parafii Siostry Franciszkanki Maryi
        Niepokalanej. Po&nbsp;Mszy Świętej można nabyć książki z&nbsp;ich
        wydawnictwa.</p>
        <p>13. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        naszej parafii. Wszystkim obchodzącym imieniny, rocznice
        i&nbsp;jubileusze składamy serdeczne życzenia. Naszym Parafianom
        i&nbsp;Gościom życzymy błogosławionej niedzieli.</p>
