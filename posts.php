        <p>1. W&nbsp;tym tygodniu oddajemy cześć świętym: w&nbsp;poniedziałek
        świętemu Bartłomiejowi Apostołowi, w&nbsp;środę NMP Częstochowskiej,
        w&nbsp;czwartek św.&nbsp;Monice, w&nbsp;piątek św.&nbsp;Augustynowi,
        w&nbsp;sobotę Janowi Chrzcicielowi w&nbsp;tajemnicy jego męczeństwa.</p>
        <p>2. Zapowiadane w&nbsp;zeszłym tygodniu prace przy czyszczeniu
        i&nbsp;renowacji posadzki w&nbsp;naszym kościele, z&nbsp;przyczyn
        niezależnych od&nbsp;nas zostały przesunięte na&nbsp;najbliższy
        tydzień. Mamy nadzieję, że&nbsp;w&nbsp;przyszłą niedzielę będziemy
        mogli się cieszyć efektami renowacji. Według planu we&nbsp;wtorek
        odbędą się prace w&nbsp;prezbiterium. A&nbsp;od&nbsp;środy
        do&nbsp;piątku w&nbsp;nawie kościoła. Gdyby ktoś dysponował czasem,
        to&nbsp;w&nbsp;poniedziałek po&nbsp;Mszy wieczornej prosimy
        o&nbsp;pomoc w&nbsp;przygotowaniu prezbiterium, a&nbsp;we&nbsp;wtorek,
        także po&nbsp;Mszy wieczornej o&nbsp;pomoc w&nbsp;przesunięciu ławek
        w&nbsp;nawie kościoła.</p>
        <p>3. W&nbsp;związku z&nbsp;planowanymi pracami nie będzie w&nbsp;tym
        tygodniu adoracji Najświętszego Sakramentu.</p>
        <p>4. Na&nbsp;naszym kościele zawisł baner z&nbsp;wileńskim
        wizerunkiem Pana Jezusa Miłosiernego, przypominający o&nbsp;odbywającej
        się w&nbsp;naszej diecezji peregrynacji. Bardzo dziękujemy
        za&nbsp;wykonanie ramy na&nbsp;obraz oraz jej zamontowanie firmie pana
        Stanisława Kacprzyka, a&nbsp;panu Mirkowi Podoleckiemu i&nbsp;jego
        ekipie za&nbsp;projekt, druk i&nbsp;zawieszenie. Dziękujemy także
        strażakom za&nbsp;pomoc przy montażu. W&nbsp;najbliższą niedzielę
        postaramy się przybliżyć znaczenie tego obrazu i&nbsp;w&nbsp;ten
        sposób rozpocząć duchowe przygotowanie do&nbsp;peregrynacji
        w&nbsp;naszej parafii, która będzie miała miejsce 8&nbsp;marca 2027
        roku.</p>
        <p>5. Spotkanie dla kandydatów do&nbsp;bierzmowania z&nbsp;klasy&nbsp;8
        będą odbywać się w&nbsp;pierwsze czwartki miesiąca. Każde spotkanie
        rozpocznie się Mszą Święto o&nbsp;18:00, a&nbsp;po&nbsp;niej katecheza
        w&nbsp;kościele. Pierwsze obowiązkowe spotkanie dla kandydatów
        do&nbsp;bierzmowania z&nbsp;klasy&nbsp;8 z&nbsp;rodzicami będzie
        3&nbsp;września, nieobecność kandydatów do&nbsp;bierzmowania prosimy
        o&nbsp;usprawiedliwienie.</p>
        <p>6. Spotkania dla ministrantów będą odbywać się w&nbsp;poniedziałki.
        Dla młodszych ministrantów i&nbsp;tych, którzy chcieliby zostać
        ministrantami zbiórki będą w&nbsp;poniedziałki o&nbsp;godz.&nbsp;16:00
        w&nbsp;kościele. Dla starszych ministrantów i&nbsp;lektorów spotkania
        będą również w&nbsp;poniedziałki, ale po&nbsp;Mszy Świętej wieczorowej,
        ok.&nbsp;18:30.</p>
        <p>7. Od&nbsp;września wznawiamy treningi drużyny LSO Sandomierz
