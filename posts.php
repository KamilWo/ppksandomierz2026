        <h3>27.&nbsp;września 2026&nbsp;r.</h3>
        <h3>XXVI&nbsp;niedziela zwykła, Rok&nbsp;A</h3>
    </div>
    <div class="col">
        <p>1. W&nbsp;tym tygodniu czcimy: w&nbsp;poniedziałek św.&nbsp;Wacława,
        męczennika, we&nbsp;wtorek świętych archaniołów Michała, Gabriela
        i&nbsp;Rafała, w&nbsp;środę św.&nbsp;Hieronima, w&nbsp;czwartek
        św.&nbsp;Teresę od&nbsp;Dzieciątka Jezus i&nbsp;w&nbsp;piątek świętych
        Aniołów Stróżów.</p>
        <p>2. Jutro o&nbsp;godzinie 15.00 na&nbsp;Rynku Starego Miasta będziemy
        modlić się Koronką do&nbsp;Bożego Miłosierdzia w&nbsp;ramach wydarzenia
        <em>Koronka na&nbsp;ulicach miast świata</em>. Serdecznie zapraszamy!
        Zachęcamy także, aby tego dnia odmówić Koronkę przy krzyżach
        i&nbsp;kapliczkach, gdzie odbywają się nabożeństwa majowe.</p>
        <p>3. Od&nbsp;środy, 1&nbsp;października, rozpoczynamy nabożeństwa
        różańcowe. Serdecznie zapraszamy do&nbsp;wspólnej modlitwy, każdego
        dnia o&nbsp;godzinie 17.30.</p>
        <p>4. W&nbsp;tym tygodniu wypadają pierwszy czwartek, piątek
        i&nbsp;sobota miesiąca.</p>
        <p>5. Chorych w&nbsp;domach będziemy odwiedzać w&nbsp;piątek
        od&nbsp;godziny 8.00.</p>
        <p>6. Spowiedź w&nbsp;piątek rano przed Mszą Świętą
        i&nbsp;po&nbsp;południu od&nbsp;godziny 17.00. Dla tych, którzy nie
        będą uczestniczyć we&nbsp;Mszy Świętej, o&nbsp;godz.&nbsp;17.30
        udzielimy komunii świętej.</p>
        <p>7. W&nbsp;sobotę różaniec wynagradzający w&nbsp;ramach nabożeństwa
        różańcowego o&nbsp;17.30.</p>
        <p>8. W&nbsp;niedzielę różaniec dla róż różańcowych i&nbsp;zmiana
        tajemnic o&nbsp;godz.&nbsp;10.45.</p>
        <p>9. Przypominamy i&nbsp;zapraszamy na&nbsp;zbiórki ministrantów
        i&nbsp;lektorów. Kandydaci i&nbsp;młodsi ministranci
        w&nbsp;poniedziałki o&nbsp;16.00 w&nbsp;kościele, starsi
        w&nbsp;poniedziałki o&nbsp;18:30. Zajęcia sportowe dla starszych
        w&nbsp;poniedziałki o&nbsp;19:30, a&nbsp;dla młodszych w&nbsp;soboty
        o&nbsp;13.00.</p>
        <p>10. Próby dziecięcej scholi parafialnej, odbywają się w&nbsp;soboty
        o&nbsp;godz.&nbsp;9.00. Serdecznie zapraszamy.</p>
        <p>11. Spotkanie dla kandydatów do&nbsp;bierzmowania z&nbsp;klasy&nbsp;8
        w&nbsp;tym tygodniu w&nbsp;pierwszy czwartek miesiąca.
        O&nbsp;godz.&nbsp;18:00 Msza święta, a&nbsp;po&nbsp;Mszy katecheza
        w&nbsp;kościele.</p>
        <p>12. Spotkanie dla dzieci pierwszokomunijnych w&nbsp;najbliższą
        sobotę w&nbsp;kościele od&nbsp;godz.&nbsp;10:00 do&nbsp;11:30.</p>
        <p>13. W&nbsp;niedzielę na&nbsp;Mszy o&nbsp;godz.&nbsp;12:30 zostaną
        poświęcone i&nbsp;wręczone dzieciom komunijnym różańce.</p>
        <p>14. W&nbsp;dniach 30&nbsp;sierpnia - 5&nbsp;września 2027&nbsp;r.
        (poniedziałek - niedziela) odbędzie się samolotowa pielgrzymka śladami
        św.&nbsp;Pawła i&nbsp;św.&nbsp;Barnaby na&nbsp;Cypr. Szczegółowe
        informacje i&nbsp;zapisy u&nbsp;ks.&nbsp;Krystiana.</p>
        <p>15. Nadal zachęcamy do&nbsp;udziału w&nbsp;pielgrzymce
        do&nbsp;Wilna, od&nbsp;30&nbsp;kwietnia do&nbsp;3&nbsp;maja
        2027&nbsp;r.</p>
        <p>16. Wojownicy Maryi zapraszają wszystkich panów na&nbsp;spotkania
        rejonowe, które odbywają się w&nbsp;kościele św.&nbsp;Józefa
        w&nbsp;Sandomierzu w&nbsp;każdą pierwszą sobotę miesiąca
        o&nbsp;godz.&nbsp;17.00. Pierwsze spotkanie w&nbsp;sobotę
        3&nbsp;października. To&nbsp;okazja, by&nbsp;we&nbsp;wspólnocie
        umacniać wiarę i&nbsp;uczyć się od&nbsp;Maryi zawierzenia Bogu
        w&nbsp;codziennym życiu.</p>
        <p>17. Zapraszają również wszystkich wiernych na&nbsp;Procesję
        Różańcową ulicami Sandomierza w&nbsp;sobotę, 10&nbsp;października
        2026&nbsp;r. Rozpoczęcie o&nbsp;godz.&nbsp;11.00 w&nbsp;kościele
        św.&nbsp;Józefa. Idąc razem z&nbsp;różańcem w&nbsp;dłoni, powierzmy
        Maryi nasze rodziny, miasto i&nbsp;Ojczyznę.</p>
        <p>18. W&nbsp;tym tygodniu swoją ziemską pielgrzymkę zakończyli nasze
        parafianki: Zofia Wachowicz, Teresa Zybała, Halina Staszałek
        i&nbsp;Edyta Franos. Polećmy je&nbsp;Bożemu miłosierdziu.</p>
        <p>19. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        parafii. Wszystkim obchodzącym imieniny, rocznice i&nbsp;jubileusze
        składamy serdeczne życzenia. Drogim Parafianom i&nbsp;Miłym Gościom
        życzymy błogosławionej niedzieli.</p>
