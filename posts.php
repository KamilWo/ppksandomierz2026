    <div class="col">
        <p>1. Dzisiejszą niedzielą, nazywaną niedzielą Dobrego Pasterza,
        rozpoczynamy tydzień modlitw o&nbsp;powołania. Pamiętajmy
        w&nbsp;codziennej modlitwie zarówno o&nbsp;klerykach formujących się
        w&nbsp;naszym seminarium, szczególnie o&nbsp;naszym parafianinie
        Pawle, jak również prośmy o&nbsp;nowe, liczne i&nbsp;święte powołania
        do&nbsp;wyłącznej służby Bożej.</p>
        <p>2. W&nbsp;piątek rozpoczynamy miesiąc maj. W&nbsp;naszym kościele
        nabożeństwa majowe codziennie o&nbsp;godz.&nbsp;17.30. Zachęcamy także
        do&nbsp;kultywowania tradycji śpiewu litanii przy kapliczkach.</p>
        <p>3. W&nbsp;tym roku ze&nbsp;względu na&nbsp;to, że&nbsp;3&nbsp;maja
        wypada w&nbsp;niedzielę, uroczystość Matki Bożej Królowej Polski
        przeniesiona jest na&nbsp;sobotę 2&nbsp;maja. Msze Święte tego dnia
        o&nbsp;godz.&nbsp;6.30, 9.30 i&nbsp;18.00.</p>
        <p>4. 1&nbsp;maja w&nbsp;pierwszy piątek miesiąca odwiedzimy chorych
        w&nbsp;domach. Początek o&nbsp;godz.&nbsp;8.00.</p>
        <p>5. Spowiedź pierwszopiątkowa od&nbsp;godz.&nbsp;17.00.</p>
        <p>6. W&nbsp;pierwszą sobotę, 2&nbsp;maja, o&nbsp;godz.&nbsp;17.00
        różaniec wynagradzający.</p>
        <p>7. W&nbsp;przyszłą niedzielę różaniec o&nbsp;godz.&nbsp;10.45,
        a&nbsp;po&nbsp;nim zmiana tajemnic różańcowych.</p>
        <p>8. W&nbsp;imieniu Księdza Rektora i&nbsp;wspólnoty seminaryjnej
        zapraszamy dzisiaj na&nbsp;Drogę Światła w&nbsp;ogrodach seminaryjnych.
        Początek o&nbsp;godz.&nbsp;19.00. Będzie to&nbsp;modlitwa
        o&nbsp;powołania w&nbsp;rozpoczynającym się Tygodniu Modlitwy
        w&nbsp;Intencji Powołań.</p>
        <p>9. Na&nbsp;dzień 1&nbsp;maja (piątek) Ksiądz Biskup udzielił
        dyspensy od&nbsp;zachowania wstrzemięźliwości od&nbsp;spożywania
        pokarmów mięsnych. Jednocześnie zachęcił wszystkich, którzy skorzystają
        z &nbsp;dyspensy do&nbsp;odmówienia Koronki do&nbsp;Bożego
        Miłosierdzia lub innej modlitwy w&nbsp;intencji pokoju
        na&nbsp;świecie.</p>
        <p>10. Serdecznie gratulujemy młodzieży, która przyjęła sakrament
        bierzmowania. Rodzicom dziękujemy za&nbsp;ofiarę złożoną przy tej
        okazji jako dar ołtarza. O&nbsp;jej wykorzystaniu poinformujemy
        w&nbsp;najbliższym czasie. Natomiast tacę z&nbsp;bierzmowania
        przekazaliśmy do&nbsp;kurii diecezjalnej na&nbsp;fundusz
        ewangelizacyjny.</p>
        <p>11. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        parafii. Wszystkim obchodzącym imieniny, rocznice i&nbsp;jubileusze
        składamy serdeczne życzenia. Wszystkim Parafianom i&nbsp;Gościom
        życzymy błogosławionej niedzieli.</p>
