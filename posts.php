    <div class="card-header">
        <h3>1.&nbsp;listopada 2026&nbsp;r.</h3>
        <h3>Uroczystość Wszystkich Świętych</h3>
    </div>
    <div class="col">
        <p>1. Dziś, <strong>1&nbsp;listopada</strong>, w&nbsp;radosną
        Uroczystość Wszystkich Świętych w&nbsp;naszym parafialnym kościele
        porządek Mszy&nbsp;św., jak w&nbsp;niedzielę. Na&nbsp;cmentarzach
        sandomierskich będą sprawowane Msze Święte: na&nbsp;cmentarzu
        komunalnym o&nbsp;godz.&nbsp;12.30, na&nbsp;cmentarzu katedralnym
        o&nbsp;godz.&nbsp;13.00 i&nbsp;Świętopawelskim
        o&nbsp;godz.&nbsp;14.00.</p>
        <p>2. <strong>Jutro - 2&nbsp;listopada</strong> – Wspomnienie
        wszystkich wiernych zmarłych, tzw.&nbsp;dzień zaduszny – Msze święte
        w&nbsp;naszym kościele <strong>o&nbsp;godz.&nbsp;6.30, 9.00
        i&nbsp;18.00</strong>.</p>
        <p>3. <strong>2&nbsp;listopada Mszę świętą o&nbsp;godzinie
        9.00</strong> będziemy sprawować w&nbsp;intencji zmarłych parafian.
        Po&nbsp;Mszy Świętej przejdziemy w&nbsp;procesji zadusznej, aby
        pomodlić się szczególnie za&nbsp;osoby zmarłe w&nbsp;tym roku.
        Na&nbsp;tę&nbsp;Mszę świętą zapraszamy zwłaszcza tych, którzy
        w&nbsp;tym roku pożegnali swoich najbliższych.</p>
        <p>4. Każdego dnia <strong>od&nbsp;1 do&nbsp;8&nbsp;listopada</strong>
        o&nbsp;godzinie 17.30 Koronka do&nbsp;Bożego Miłosierdzia
        za&nbsp;zmarłych polecanych w&nbsp;wypominkach jednorazowych.
        Za&nbsp;zmarłych polecanych w&nbsp;wypominkach jednorocznych będziemy
        modlić się od&nbsp;przyszłej niedzieli o&nbsp;godz.&nbsp;9.00.</p>
        <p>5. Przypominamy o&nbsp;możliwości zyskania odpustu zupełnego
        i&nbsp;ofiarowania go&nbsp;za&nbsp;zmarłych od&nbsp;1
        do&nbsp;8&nbsp;listopada. Warunkiem uzyskania odpustu jest nawiedzenie
        cmentarza i&nbsp;modlitwa za&nbsp;zmarłych oraz wypełnienie zwykłych
        warunków, tj.&nbsp;wyzbycie przywiązania się do&nbsp;grzechu,
        przystąpienie do&nbsp;komunii św.&nbsp;w&nbsp;dniu nawiedzenia
        cmentarza, modlitwa "Ojcze nasz" i&nbsp;"Wierzę w&nbsp;Boga",
        i&nbsp;jakakolwiek modlitwa w&nbsp;intencjach wyznaczonych
        na&nbsp;dany dzień przez papieża.</p>
        <p>6. W&nbsp;tym tygodniu pierwszy czwartek, piątek i&nbsp;sobota
        miesiąca. Chorych w&nbsp;domach odwiedzimy w&nbsp;piątek
        od&nbsp;godz.&nbsp;8.00. Różaniec wynagradzający w&nbsp;sobotę
        o&nbsp;godz.&nbsp;17.00.</p>
        <p>7. Dzisiejsza uroczystość przypomina, że&nbsp;świętość jest
        powołaniem każdego człowieka. W&nbsp;najbliższy <strong>czwartek,
        5&nbsp;listopada</strong>, rozpoczynają się 33&nbsp;dniowe rekolekcje
        w&nbsp;duchu św.&nbsp;Ludwika Marii Grignion de&nbsp;Monfort. Jest
        to&nbsp;zaproszenie, by&nbsp;rzez Maryję zbliżyć się do&nbsp;Jezusa
        i&nbsp;na&nbsp;nowo powierzyć Mu&nbsp;swoje życie. Takim oddaniem żyli
        św.&nbsp;Jan Paweł&nbsp;II, bł.&nbsp;kard. Wyszyński
        i&nbsp;św.&nbsp;Maksymilian Maria Kolbe – i&nbsp;my&nbsp;możemy pójść
        ich śladem. Rozpoczęcie rekolekcji w&nbsp;czwartek, w&nbsp;kościele
        seminaryjnym o&nbsp;godz.&nbsp;17.30.</p>
        <p>8. W&nbsp;najbliższy czwartek, <strong>5 listopada</strong>,
        na&nbsp;Mszę Świętą o&nbsp;godz.&nbsp;18.00 zapraszamy kandydatów
        do&nbsp;bierzmowania z&nbsp;klasy VIII. Po&nbsp;Mszy Świętej
        katecheza.</p>
        <p>9. W&nbsp;najbliższą sobotę, <strong>7&nbsp;listopada</strong>,
        na&nbsp;godz.&nbsp;10.00 zapraszamy na&nbsp;spotkanie dzieci
        pierwszokomunijne oraz ich rodziców. Dzieci będą miały swoje spotkanie
        w&nbsp;kościele, a&nbsp;rodzice w&nbsp;sali w&nbsp;budynku
        jadłodajni.</p>
        <p>10. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        parafii. Wszystkim obchodzącym imieniny, rocznice i&nbsp;jubileusze
        składamy serdeczne życzenia. Drogim Parafianom i&nbsp;Miłym Gościom
        życzymy błogosławionej niedzieli.</p>
