        <p>2. W&nbsp;przyszłą sobotą, 25&nbsp;lipca, swoje imieniny obchodzi
        ksiądz biskup Krzysztof Nitkiewicz, ordynariusz naszej diecezji.
        Pamiętajmy w&nbsp;modlitwie o&nbsp;naszym Pasterzu.</p>
        <p>3. W&nbsp;sobotę po&nbsp;Mszy Świętej wieczornej poświęcimy pojazdy
        mechaniczne.</p>
        <p>4. W&nbsp;przyszłą niedzielę będzie możliwość wesprzeć materialnie
        chorą Wiktorię Bednarz. Wiktoria przeszła już operacje głowy, serca
        i&nbsp;nóg. Czeka ją&nbsp;operacja kręgosłupa i&nbsp;czaszki, bez
        której dojdzie do&nbsp;ucisku i&nbsp;uszkodzeń w&nbsp;mózgu. Wiktoria
        wymaga intensywnej rehabilitacji oraz specjalistycznych terapii koszty
        w&nbsp;skali roku są&nbsp;ogromne. O&nbsp;możliwość zbiórki zwrócili
        się do&nbsp;nas rodzice. Otrzymaliśmy także pismo z&nbsp;Kurii
        Diecezjalnej potwierdzające autentyczność prośby. Zachęcamy,
        w&nbsp;miarę możliwości do&nbsp;wsparcia.</p>
        <p>5. W&nbsp;dniach od&nbsp;29&nbsp;lipca do&nbsp;8&nbsp;sierpnia 2027
        roku odbędą Światowe Dni Młodzieży w&nbsp;Korei Południowej. Koszt
        wyjazdu to&nbsp;ok.&nbsp;10&nbsp;000&nbsp;zł. Szczegółowe informacje
        i&nbsp;zapisy u&nbsp;ks.&nbsp;Krystiana.</p>
        <p>6. W&nbsp;przyszłym roku planujemy dwie pielgrzymki. W&nbsp;dniach
        od&nbsp;30&nbsp;kwietnia do&nbsp;3&nbsp;maja odbędzie się pielgrzymka
        śladami Bożego Miłosierdzia do&nbsp;Wilna, jako wotum wdzięczności
        za&nbsp;czas peregrynacji obrazu Jezusa Miłosiernego w&nbsp;naszej
        parafii. Z&nbsp;kolei w&nbsp;drugiej połowie sierpnia odbędzie się
        pielgrzymka na&nbsp;Cypr śladami św.&nbsp;Pawła. Szczegółowe
        informacje podamy we&nbsp;wrześniu.</p>
        <p>7. Bardzo dziękujemy raz jeszcze Panom Wacławowi i&nbsp;Leszkowi
        za&nbsp;konserwację i&nbsp;odnowienie drzwi wejściowych
        do&nbsp;naszego kościoła.</p>
        <p>8. W&nbsp;ostatnim czasie swoją ziemską pielgrzymkę zakończyli nasi
        parafianie: Sławomir Litwiński, Kazimiera Sadaj, Julian Dragan,
        Aleksandra Kowalska, Alfred Czech. Polećmy ich Bożemu miłosierdziu.</p>
        <p>9. Dziękujemy za&nbsp;każde duchowe i&nbsp;materialne wsparcie
        parafii. Wszystkim obchodzącym imieniny, rocznice i&nbsp;jubileusze
        składamy serdeczne życzenia. Naszym Parafianom i&nbsp;Gościom życzymy
        błogosławionej niedzieli i&nbsp;spokojnych wakacji.</p>
