        się w&nbsp;naszej diecezji w&nbsp;dniach
        <strong>12–18&nbsp;października</strong>. W&nbsp;Sandomierzu
        zaplanowano następujące wydarzenia:</p>
        <ul>
            <li><strong>W&nbsp;poniedziałek, 12&nbsp;października</strong>,
