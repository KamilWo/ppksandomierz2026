        <p>1. Jutro obchodzimy Uroczystość Świętych Apostołów Piotra
        i&nbsp;Pawła. Msze&nbsp;św. o&nbsp;godz.&nbsp;6.30 i&nbsp;18.00. Taca
        tego dnia przeznaczona jest na&nbsp;Stolicę Apostolską.</p>
        <p>2. W&nbsp;przyszłą niedzielę w&nbsp;kościele, pół godziny przed
        Mszą&nbsp;św., która sprawowana jest o&nbsp;godz.&nbsp;11.15 –
        adoracja Najświętszego Sakramentu połączona z&nbsp;modlitwą różańcową
        i&nbsp;zmiana tajemnic różańcowych. Zapraszamy do&nbsp;wspólnotowej
        modlitwy.</p>
        <p>3. W&nbsp;tym tygodniu pierwszy czwartek, piątek i&nbsp;sobota
        miesiąca. Spowiedź w&nbsp;piątek od&nbsp;godz.&nbsp;17.00.</p>
        <p>4. W&nbsp;sobotę o&nbsp;godz.&nbsp;17.15 różaniec wynagradzający
        poprowadzi Legion Maryi z&nbsp;naszej parafii.</p>
        <p>5. Przypominamy, że&nbsp;w&nbsp;miesiącach wakacyjnych nie
        odwiedzamy chorych w&nbsp;domach. Gdyby była potrzeba spowiedzi,
        komunii świętej lub namaszczenia chorych prosimy o&nbsp;indywidualne
        telefoniczne zgłoszenie.</p>
        <p>6. W&nbsp;dniach 4-12&nbsp;sierpnia odbędzie się piesza pielgrzymka
        z&nbsp;Sandomierza na&nbsp;Jasną Górę. Szczegóły na&nbsp;plakacie
        w&nbsp;gablocie.</p>
        <p>7. Dziękujemy serdecznie Panom Wacławowi Miszczakowi
        i&nbsp;Leszkowi Czajce za&nbsp;pracę przy odnowieniu drzwi wejściowych
        do&nbsp;naszej świątyni.</p>
        <p>8. Burmistrz Sandomierza Paweł Niedźwiedź zaprasza mieszkańców
        Sandomierza na&nbsp;wydarzenie pod nazwą „Biała Sobota”, które
        odbędzie się 4&nbsp;lipca w&nbsp;godzinach od&nbsp;9.00 do&nbsp;16.00
        na&nbsp;sandomierskim Bulwarze nad Wisłą. W&nbsp;ramach akcji
        oferowane będą bezpłatne badania, konsultacje, porady między innymi
        badania skóry pod kątem czerniaka, badanie gęstości kości, słuchu,
        badania cytologiczne i&nbsp;mammograficzne, badania wad postawy
        u&nbsp;dzieci, pomiary glikemii, ciśnienia tętniczego i&nbsp;wiele
        innych. Szczegóły na&nbsp;plakacie w&nbsp;gablocie.</p>
        <p>9. W&nbsp;tym tygodniu kancelaria parafialna nie będzie czynna
        w&nbsp;poniedziałek po&nbsp;Mszy Świętej. W&nbsp;sprawach pilnych
        zapraszamy po&nbsp;Mszy porannej lub po&nbsp;umówieniu telefonicznym.
        We&nbsp;wtorek, czwartek i&nbsp;piątek kancelaria czynna będzie
        po&nbsp;Mszy wieczornej, od&nbsp;godziny ok.&nbsp;18.40.</p>
        <p>10. W&nbsp;ostatnim czasie swoją ziemską pielgrzymkę zakończyli
        nasi parafianie: Monika Bernaś (która przez lata dbała o&nbsp;porządek
        w&nbsp;naszym kościele), Stanisława Banasiewicz oraz Czesław Zeliaś.
        Polećmy ich Bożemu miłosierdziu.</p>
        <p>11. Dziękujemy za&nbsp;wszelkie duchowe i&nbsp;materialne wsparcie
        parafii. Wszystkim obchodzącym imieniny, rocznice i&nbsp;jubileusze
        składamy serdeczne życzenia. Wszystkim Parafianom i&nbsp;Gościom
        życzymy błogosławionej niedzieli.</p>
