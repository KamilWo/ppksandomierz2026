        w&nbsp;każdy poniedziałek na&nbsp;hali sportowej „pod balonem” przy
        szkole podstawowej nr&nbsp;1 od&nbsp;19:30 do&nbsp;21:00. Dla młodszych
        termin zajęć na&nbsp;hali zostanie podany w&nbsp;późniejszym czasie.</p>
        <p>8. W&nbsp;tym tygodniu swoją ziemską pielgrzymkę zakończyli nasi
